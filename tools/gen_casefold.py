#!/usr/bin/env python3
"""Generates src/zbcasefold.inc from Unicode's full case folding
(CaseFolding.txt statuses C and F; S is the simple folding that F supersedes,
and str.casefold() applies C+F, so U+1E9E folds to "ss"), as exposed by
Python's str.casefold() (the Unicode data of the interpreter running this
script). The include holds two constants, ZB_CASEFOLD_KEYS (the code points
that change, ascending, for a binary search) and ZB_CASEFOLD_VALUES (what each
folds to: three code points, 0 for none).

The committed table was built with Unicode 16.0.0. The script exits non-zero
under any other Unicode version, so an older or newer Python cannot silently
change the table. To regenerate, use a Python whose unicodedata.unidata_version
is 16.0.0, or, when moving to a newer Unicode, change EXPECTED_UNICODE_VERSION
below on purpose and review the diff:

    python3 tools/gen_casefold.py > src/zbcasefold.inc
"""
import sys
import unicodedata

EXPECTED_UNICODE_VERSION = "16.0.0"

if unicodedata.unidata_version != EXPECTED_UNICODE_VERSION:
    sys.stderr.write("gen_casefold.py: Unicode data is %s, the committed table was built with %s; "
                     "use a Python with that version (see the docstring).\n"
                     % (unicodedata.unidata_version, EXPECTED_UNICODE_VERSION))
    sys.exit(1)

keys = []
values = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    folded = chr(cp).casefold()
    if folded == chr(cp):
        continue
    cps = [ord(c) for c in folded]
    assert len(cps) <= 3
    cps += [0] * (3 - len(cps))
    keys.append(cp)
    values.append(cps)

def chunks(items, per_line):
    for i in range(0, len(items), per_line):
        yield items[i:i + per_line]

print("{ Generated by tools/gen_casefold.py from Unicode %s full case folding"
      " (CaseFolding.txt C+F). Do not edit. }" % unicodedata.unidata_version)
print("const")
print("    ZB_CASEFOLD_COUNT = %d;" % len(keys))
print("    ZB_CASEFOLD_KEYS: array[0..%d] of LongInt = (" % (len(keys) - 1))
lines = [", ".join("$%04X" % k for k in c) for c in chunks(keys, 12)]
print(",\n".join("        " + l for l in lines))
print("    );")
print("    ZB_CASEFOLD_VALUES: array[0..%d] of LongInt = (" % (len(keys) * 3 - 1))
flat = [v for cps in values for v in cps]
lines = [", ".join("$%04X" % v for v in c) for c in chunks(flat, 12)]
print(",\n".join("        " + l for l in lines))
print("    );")
sys.stderr.write("%d entries\n" % len(keys))
