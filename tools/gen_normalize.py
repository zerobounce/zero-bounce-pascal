#!/usr/bin/env python3
"""Generates src/zbnormalize.inc: the Unicode canonical decomposition and the
canonical combining classes the redaction fold needs (NFD, with the canonical
ordering of combining marks), from the data of the Python running this script.

The include holds
  ZB_NFD_KEYS     the code points that have a canonical decomposition (no
                  <compat> tag), ascending, Hangul syllables left out (they are
                  decomposed by the algorithm in the code);
  ZB_NFD_OFFSETS  for the K-th key, where its full decomposition starts in
                  ZB_NFD_POOL (the next entry is where it ends);
  ZB_NFD_POOL     the decompositions, applied recursively until nothing more
                  decomposes (what unicodedata.normalize('NFD', ...) gives);
  ZB_CCC_*        ranges of code points with the same non-zero canonical
                  combining class (start, end, class), ascending.

The committed table was built with Unicode 16.0.0. The script exits non-zero
under any other Unicode version (as tools/gen_casefold.py does). To
regenerate, use a Python whose unicodedata.unidata_version is 16.0.0:

    python3 tools/gen_normalize.py > src/zbnormalize.inc
"""
import sys
import unicodedata

EXPECTED_UNICODE_VERSION = "16.0.0"

if unicodedata.unidata_version != EXPECTED_UNICODE_VERSION:
    sys.stderr.write("gen_normalize.py: Unicode data is %s, the committed table was built with %s; "
                     "use a Python with that version (see the docstring).\n"
                     % (unicodedata.unidata_version, EXPECTED_UNICODE_VERSION))
    sys.exit(1)

keys = []
offsets = []
pool = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
        continue
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        continue
    full = [ord(c) for c in unicodedata.normalize("NFD", chr(cp))]
    assert full != [cp]
    keys.append(cp)
    offsets.append(len(pool))
    pool.extend(full)
offsets.append(len(pool))

ranges = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = unicodedata.combining(chr(cp))
    if c == 0:
        continue
    if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == c:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, c])

def chunks(items, per_line):
    for i in range(0, len(items), per_line):
        yield items[i:i + per_line]

def emit(name, values, fmt):
    print("    %s: array[0..%d] of LongInt = (" % (name, len(values) - 1))
    lines = [", ".join(fmt % v for v in c) for c in chunks(values, 12)]
    print(",\n".join("        " + l for l in lines))
    print("    );")

print("{ Generated by tools/gen_normalize.py from Unicode %s (canonical"
      " decompositions and combining classes). Do not edit. }" % unicodedata.unidata_version)
print("const")
print("    ZB_NFD_COUNT = %d;" % len(keys))
emit("ZB_NFD_KEYS", keys, "$%04X")
emit("ZB_NFD_OFFSETS", offsets, "%d")
emit("ZB_NFD_POOL", pool, "$%04X")
print("    ZB_CCC_COUNT = %d;" % len(ranges))
emit("ZB_CCC_STARTS", [r[0] for r in ranges], "$%04X")
emit("ZB_CCC_ENDS", [r[1] for r in ranges], "$%04X")
emit("ZB_CCC_VALUES", [r[2] for r in ranges], "%d")
sys.stderr.write("%d decompositions (longest %d), %d combining ranges\n"
                 % (len(keys), max(offsets[i + 1] - offsets[i] for i in range(len(keys))), len(ranges)))
